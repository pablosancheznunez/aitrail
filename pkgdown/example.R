# Builds the examples published on the website: the HTML report and the
# disclosure statements of the example project, and the JSON Schema.
library(aitrail)

out <- "_site/example"
dir.create(out, recursive = TRUE, showWarnings = FALSE)
project <- ait_example()

ait_report(project, file.path(out, "report.html"))
ait_report(project, file.path(out, "report-es.html"), lang = "es")

esc <- function(x) gsub("<", "&lt;", gsub("&", "&amp;", x, fixed = TRUE), fixed = TRUE)
block <- function(title, text) c(sprintf("<h2>%s</h2>", title), sprintf("<pre>%s</pre>", esc(text)))
html <- c(
  '<!doctype html><html lang="en"><head><meta charset="utf-8">',
  '<meta name="viewport" content="width=device-width, initial-scale=1">',
  "<title>aitrail example disclosure</title>",
  '<link rel="icon" href="../favicon.svg" type="image/svg+xml">',
  "<style>",
  ":root{--ink:#1b2430;--muted:#5b6575;--bg:#fbfbfa;--card:#fff;--line:#e2e4e8;--link:#1f5f5b}",
  "@media (prefers-color-scheme:dark){:root{--ink:#e7eaee;--muted:#a7afbb;--bg:#14181d;--card:#1c2229;--line:#2d3540;--link:#6cc2bb}}",
  "body{margin:0;background:var(--bg);color:var(--ink);font:16px/1.55 system-ui,sans-serif}",
  "main{max-width:900px;margin:0 auto;padding:32px 16px}h1{font-family:Georgia,serif;font-weight:normal}",
  "pre{white-space:pre-wrap;background:var(--card);border:1px solid var(--line);border-radius:8px;padding:12px 16px}",
  "p{color:var(--muted)}a{color:var(--link)}",
  "</style></head><body><main>",
  '<p><a href="../">aitrail</a> / example</p>',
  "<h1>Example disclosure statements</h1>",
  "<p>Generated by <code>ait_disclosure()</code> from the log of the example project, a fictitious study (synthetic data). Review and adapt any statement to the policy of the journal or funder.</p>",
  block("Short statement (English)", ait_disclosure(project)),
  block("Short statement (Spanish)", ait_disclosure(project, lang = "es")),
  block("Full appendix (Markdown)", ait_disclosure(project, style = "full")),
  block("Machine-readable (JSON)", ait_disclosure(project, style = "json")),
  '<p>See also the <a href="report.html">HTML report</a> (<a href="report-es.html">en espa&ntilde;ol</a>).</p>',
  "</main></body></html>"
)
writeLines(enc2utf8(html), file.path(out, "disclosure.html"), useBytes = TRUE)

dir.create("_site/schema", showWarnings = FALSE)
file.copy(system.file("schema", "ai-log.schema.json", package = "aitrail"), "_site/schema/", overwrite = TRUE)
